-- ============================================================
-- V60 · 放开 cash_flow.amount 的取值域(v1.22 FR-595 / FR-596)
-- ============================================================
--
-- 为什么改:
--   真实账单里有 **0 元行**(全额优惠券 / 积分抵扣)和 **负数行**(退款冲正、红字)。
--   v1.21 把它们挡在导入之外,页面上写「不能捞」—— 用户被单方面否决,
--   而且不给理由(理由其实是这条 CHECK,他看不到)。
--   维护者的判断:两者都应该能录,负数**原样记负数**。
--
-- 为什么是 DROP 而不是改成别的:
--   · CHECK (amount >= 0) 不够 —— 负数也要能录
--   · CHECK (amount <> 0)  与「0 元要允许导入」直接冲突
--   · 保留约束、在应用层把负数存成正数 + 方向标记 → 那是「取绝对值」的变体,
--     报表侧要处处记得乘回去,漏一处就把一笔退款画成一笔消费
--
-- 对线上现有数据的影响(prod 跑着真实家庭数据,每版必答):
--   **零**。这里只 DROP 约束,不 UPDATE / DELETE 任何行。
--   既有行全部 > 0,放宽之后天然满足。历史指标逐分不变。
--
-- 老 jar 见到这个 schema 能跑吗:
--   **能**。老 jar 只写正数,约束放宽对它完全无感。
--   (项目惯例:回滚只回 jar 不回 DB。若真要回滚 schema,
--    得先确认库里没有 ≤0 的行 —— 那是人工动作,不进自动回滚路径。)
--
-- 放开之后谁要跟着表态:
--   代码里有几处把「≤ 0」当成「没有数据」,放开后会**静默出错**
--   (最危险的是支出构成段会被整段判成「没数据」直接隐藏)。
--   清单与处置见 tech-design/v1.22.md §三,护栏 v1220-NO-POSITIVE-ASSUMPTION。
--
-- 不动 transfer 表上的 ck_transfer_amount:划转不在本版范围内。
-- ============================================================

ALTER TABLE cash_flow DROP CHECK ck_cash_flow_amount;
